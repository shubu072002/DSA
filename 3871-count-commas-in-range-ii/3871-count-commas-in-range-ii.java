class Solution {
    public long countCommas(long n) {
        if(n<1000L){
            return 0;
        }
        if(n<1000000L){
            return n-1000+1;
        }
        if(n<1000000000L){
            return (n-1000000+1)*2 + (999999-1000+1);
        }
        if(n<1000000000000L){
            return (n-1000000000+1)*3+(999999999-1000000+1)*2+(999999-1000+1);
        }
        if(n<1000000000000000L){
            return (n-1000000000000L+1)*4+(999999999999L-1000000000L+1)*3+(999999999L-1000000L+1)*2+(999999L-1000L+1);
        }
          return (n - 1000000000000000L + 1) * 5
             + (999999999999999L - 1000000000000L + 1) * 4
             + (999999999999L - 1000000000L + 1) * 3
             + (999999999L - 1000000L + 1) * 2
             + (999999L - 1000L + 1);
    }
}